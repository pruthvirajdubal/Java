public class programm153 {

    public static void main(String[] args) {
        
        int a=10,b=5;char op='+';

        if(op=='+')
            System.out.println(a+b);

        else if(op=='-')
            System.out.println(a-b);
        else if(op=='*')
            System.out.println(a*b);
        else  if(op=='/')
            System.out.println(a/b);
    }
    
}
